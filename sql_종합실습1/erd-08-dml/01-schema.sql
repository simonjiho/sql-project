\set ON_ERROR_STOP on

-- psql에서 postgres 데이터베이스에 접속한 상태로 실행한다.
SELECT 'CREATE DATABASE academic_management'
WHERE NOT EXISTS (
    SELECT 1 FROM pg_database WHERE datname = 'academic_management'
)\gexec

\connect academic_management

BEGIN;

DROP SCHEMA IF EXISTS academic CASCADE;
CREATE SCHEMA academic;
SET search_path TO academic, public;

CREATE TYPE student_status AS ENUM ('ENROLLED', 'LEAVE', 'GRADUATED', 'EXPELLED');
CREATE TYPE professor_status AS ENUM ('ACTIVE', 'RETIRED');
CREATE TYPE course_status AS ENUM ('RECRUITING', 'CLOSED', 'CANCELLED');
CREATE TYPE enrollment_status AS ENUM ('ENROLLED', 'CANCELLED');
CREATE TYPE grade_code AS ENUM ('A+', 'A0', 'B+', 'B0', 'C+', 'C0', 'D+', 'D0', 'F');

CREATE TABLE department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code VARCHAR(20) NOT NULL UNIQUE,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE student (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number VARCHAR(20) NOT NULL UNIQUE,
    student_name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    grade_year SMALLINT NOT NULL CHECK (grade_year BETWEEN 1 AND 4),
    academic_status student_status NOT NULL DEFAULT 'ENROLLED',
    admission_date DATE NOT NULL CHECK (admission_date <= CURRENT_DATE),
    phone_number VARCHAR(30),
    department_id BIGINT NOT NULL REFERENCES department(department_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE professor (
    professor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number VARCHAR(20) NOT NULL UNIQUE,
    professor_name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    employment_status professor_status NOT NULL DEFAULT 'ACTIVE',
    department_id BIGINT NOT NULL REFERENCES department(department_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE subject (
    subject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR(20) NOT NULL UNIQUE,
    subject_name VARCHAR(100) NOT NULL,
    credits SMALLINT NOT NULL CHECK (credits IN (1, 2, 3)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE course_offering (
    class_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subject(subject_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    professor_id BIGINT NOT NULL REFERENCES professor(professor_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    opening_year SMALLINT NOT NULL CHECK (opening_year BETWEEN 2000 AND 2100),
    semester SMALLINT NOT NULL CHECK (semester IN (1, 2)),
    section VARCHAR(10) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity >= 1),
    opening_status course_status NOT NULL DEFAULT 'RECRUITING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (subject_id, opening_year, semester, section)
);

CREATE TABLE enrollment (
    enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES student(student_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    class_id BIGINT NOT NULL REFERENCES course_offering(class_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    enrollment_status enrollment_status NOT NULL DEFAULT 'ENROLLED',
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ,
    grade grade_code,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (student_id, class_id),
    CHECK (
        (enrollment_status = 'ENROLLED' AND cancelled_at IS NULL)
        OR
        (enrollment_status = 'CANCELLED' AND cancelled_at IS NOT NULL)
    ),
    CHECK (NOT (enrollment_status = 'CANCELLED' AND grade IS NOT NULL))
);

CREATE INDEX ix_student_department ON student(department_id);
CREATE INDEX ix_professor_department ON professor(department_id);
CREATE INDEX ix_course_subject ON course_offering(subject_id);
CREATE INDEX ix_course_professor ON course_offering(professor_id);
CREATE INDEX ix_enrollment_student ON enrollment(student_id);
CREATE INDEX ix_enrollment_class ON enrollment(class_id);

COMMIT;

\echo '스키마와 테이블 생성 완료'
\dt academic.*
