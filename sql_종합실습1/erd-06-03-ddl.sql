CREATE FUNCTION "audit"."is_valid_changed_columns"(p_columns text[])
RETURNS boolean
LANGUAGE sql
IMMUTABLE
STRICT
PARALLEL SAFE
AS $$
  SELECT
    NOT EXISTS (
      SELECT 1
      FROM unnest(p_columns) AS item(column_name)
      WHERE column_name IS NULL OR btrim(column_name) = ''
    )
    AND cardinality(p_columns) = (
      SELECT COUNT(DISTINCT column_name)
      FROM unnest(p_columns) AS item(column_name)
    );
$$;

