  "result_snapshot" jsonb,
  "recorded_at" timestamptz NOT NULL,
  CONSTRAINT "chk_disposal_target_period" CHECK (target_period_to > target_period_from),
  CONSTRAINT "chk_disposal_deleted_count" CHECK (deleted_record_count is null or deleted_record_count >= 0),
  CONSTRAINT "chk_disposal_executor" CHECK ((execution_status = 'APPROVED' and executed_by_actor_id is null and executor_code_snapshot is null and executor_name_snapshot is null and executed_at is null) or (execution_status in ('RUNNING', 'COMPLETED', 'PARTIAL', 'FAILED') and executed_by_actor_id is not null and executor_code_snapshot is not null and executor_name_snapshot is not null)),
