CREATE TABLE "audit"."change_record" (
  "change_record_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "change_operation_id" bigint NOT NULL,
  "record_sequence" integer NOT NULL,
  "operation_type" audit.change_operation_type NOT NULL,
  "target_type" varchar(50) NOT NULL,
  "target_id_snapshot" bigint NOT NULL,
  "business_key_snapshot" jsonb NOT NULL,
  "before_snapshot" jsonb,
  "after_snapshot" jsonb,
  "changed_columns" text[] NOT NULL DEFAULT ARRAY[]::text[],
  "student_number_tag" varchar(20),
  "subject_code_tag" varchar(20),
  "opening_year_tag" smallint,
  "semester_tag" smallint,
  "section_tag" varchar(10),
  "snapshot_schema_version" integer NOT NULL,
  "recorded_at" timestamptz NOT NULL,
  CONSTRAINT "chk_change_record_sequence" CHECK (record_sequence >= 1),
  CONSTRAINT "chk_change_record_schema_version" CHECK (snapshot_schema_version >= 1),
  CONSTRAINT "chk_change_record_snapshots" CHECK ((operation_type = 'CREATE' and before_snapshot is null and after_snapshot is not null) or (operation_type = 'UPDATE' and before_snapshot is not null and after_snapshot is not null) or (operation_type = 'DELETE' and before_snapshot is not null and after_snapshot is null)),
  CONSTRAINT "chk_change_record_changed_columns_valid" CHECK (audit.is_valid_changed_columns(changed_columns)),
  CONSTRAINT "chk_change_record_changed_columns_required" CHECK (operation_type <> 'UPDATE' or cardinality(changed_columns) >= 1),
  CONSTRAINT "chk_change_record_class_tags" CHECK ((subject_code_tag is null and opening_year_tag is null and semester_tag is null and section_tag is null) or (subject_code_tag is not null and opening_year_tag is not null and semester_tag in (1, 2) and section_tag is not null))
);

