-- 문항 2. 모든 학생 기준으로 수강을 붙이고, 과목(없으면 NULL)까지 보이기
--   기대 행 수: 2,400 (수강 2,300 + 수강 없는 학생 100)
-- ------------------------------------------------------------
SELECT s.student_id, s.name, e.course
FROM lab.student s
LEFT JOIN lab.enroll e
       ON e.student_id = s.student_id;
